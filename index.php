                if (targetEl) {
                    e.preventDefault();
                    const offset = header.offsetHeight + 16;
                    const targetPosition = targetEl.getBoundingClientRect().top + window.pageYOffset - offset;

                    window.scrollTo({
                        top: targetPosition,
                        behavior: 'smooth'
                    });
                }
            });
        });

